"""Compare PiLens identities with the Ramanujan Machine's published π formulas.

Reference data: the "euler2ai" dataset (Raz et al., "From Euler to AI: Unifying Formulas
for Mathematical Constants", arXiv:2502.17533; github.com/RamanujanMachine/euler2ai):
canonical forms of 149 π formulas harvested from arXiv papers, plus 22 representatives
generated by their conservative matrix field (CMF). Convert it with
``scripts/import_euler2ai.py`` to ``data/ramanujan/euler2ai_pi.json``.

Two checks per PiLens core:

1. **Same core**: the reference fraction reduces to the same core as ours under PiLens's
   own equivalences (index shift, scaling, polynomial equivalence). Then it is the same
   formula, full stop.
2. **Same fingerprint**: the two "dynamical metrics" that the paper uses to cluster
   formulas before proving them equivalent: the irrationality measure δ and the
   convergence rate r, both at depth 2000 (definitions as in their ``unifier/pcf.py``).
   Formulas related by their transformations (coboundaries, Mobius maps) keep δ; r is kept
   by coboundaries and multiplied by k by a k-fold. A δ match with r equal or in a small
   integer ratio is strong evidence that ours is a known formula in disguise. It is not a
   proof, but it is the same first step the paper uses.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import gmpy2
from gmpy2 import mpz

from . import gcf
from .sources import data_dir

DEPTH = 2000


def reference_path() -> Path:
    return data_dir() / "ramanujan" / "euler2ai_pi.json"


def load_reference() -> list[dict]:
    p = reference_path()
    if not p.exists():
        raise FileNotFoundError(f"{p} missing: see scripts/import_euler2ai.py")
    return json.loads(p.read_text(encoding="utf-8"))


def _peval(c, n):
    v = mpz(0)
    for x in reversed(c):
        v = v * n + x
    return v


def dynamics(a, b, depth: int = DEPTH) -> dict:
    """δ and r at ``depth`` with the limit approximated at 2·depth (as in euler2ai)."""
    p_prev, q_prev = mpz(1), mpz(0)
    p, q = _peval(a, 0), mpz(1)
    snap = None
    for n in range(1, 2 * depth + 1):
        an, bn = _peval(a, n), _peval(b, n)
        p, p_prev = an * p + bn * p_prev, p
        q, q_prev = an * q + bn * q_prev, q
        if n == depth:
            snap = (p, q)
    pd, qd = snap
    if qd == 0 or q == 0:
        return {"delta": None, "r": None}
    num = abs(pd * q - p * qd)
    if num == 0:
        return {"delta": None, "r": None}
    with gmpy2.context(gmpy2.get_context(), precision=128):
        ln = lambda z: gmpy2.log(gmpy2.mpfr(abs(z)))
        ln_err = ln(num) - ln(qd) - ln(q)
        r = abs(float(ln_err) / depth)
        g = gmpy2.gcd(pd, qd)
        qr = abs(qd // g)
        delta = None if qr <= 1 else float(-(1 + ln_err / ln(qr)))
    return {"delta": delta, "r": r}


def results_path() -> Path:
    return data_dir() / "ramanujan" / "comparison.json"


def load_results() -> dict:
    p = results_path()
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def _ratio_label(r1: float, r2: float, tol: float = 0.03) -> str | None:
    if not (r1 and r2):
        return None
    for k in (1, 2, 3, 4):
        for x, y, lab in ((r1, r2 * k, f"ours = {k}× theirs"), (r2, r1 * k, f"theirs = {k}× ours")):
            if abs(x - y) <= tol * max(x, y):
                return "same rate" if k == 1 else lab
    return None


def run_compare(depth: int = DEPTH, delta_tol: float = 0.005, log=print) -> dict:
    from .novelty import collect_cores, core_form

    ref = load_reference()
    log(f"reference: {len(ref)} π fractions ({sum(r['kind'] == 'literature' for r in ref)} from the "
        f"literature, {sum(r['kind'] == 'cmf' for r in ref)} CMF representatives)")
    for r in ref:
        r["core"] = gcf.family_key(tuple(r["a"]), tuple(r["b"])) if len(r["a"]) <= 3 and len(r["b"]) <= 5 else None
        r["dyn"] = dynamics(r["a"], r["b"], depth)
    ref_cores = {r["core"]: r for r in ref if r["core"]}
    cores = collect_cores(("pi",))
    out = {}
    log(f"comparing {len(cores)} PiLens π cores ...")
    for (_, core), info in cores.items():
        rep = info["rep"]
        ca, cb = core_form(rep["a"], rep["b"])
        dyn = dynamics(ca, cb, depth)
        res = {"core": core, "fraction": gcf.gcf_str(ca, cb), "relation": rep["relation"],
               "variants": info["variants"], "delta": dyn["delta"], "r": dyn["r"], "exact": None, "fingerprint": []}
        if core in ref_cores:
            x = ref_cores[core]
            res["exact"] = {"kind": x["kind"], "index": x["index"], "limit": x["limit"],
                            "a": x["a"], "b": x["b"], "source": x["first_source"]}
        if dyn["delta"] is not None:
            for x in ref:
                d2 = x["dyn"]["delta"]
                if d2 is None or abs(d2 - dyn["delta"]) > delta_tol:
                    continue
                res["fingerprint"].append({"kind": x["kind"], "index": x["index"], "limit": x["limit"],
                                           "a": x["a"], "b": x["b"], "delta": d2, "r": x["dyn"]["r"],
                                           "rate": _ratio_label(dyn["r"], x["dyn"]["r"]),
                                           "source": x["first_source"]})
            res["fingerprint"].sort(key=lambda m: (m["rate"] is None, abs(m["delta"] - dyn["delta"])))
        strong = [m for m in res["fingerprint"] if m["rate"]]
        res["status"] = ("same formula" if res["exact"] else
                         "fingerprint matches a known formula" if strong else
                         "δ only" if res["fingerprint"] else "no match")
        out[core] = res
        tag = f"δ={dyn['delta']:.4f} r={dyn['r']:.4f}" if dyn["delta"] is not None else "δ undefined"
        log(f"  [{res['status']}] {res['fraction']} -> {rep['relation']}  ({tag})")
    results_path().parent.mkdir(parents=True, exist_ok=True)
    results_path().write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")
    counts: dict[str, int] = {}
    for v in out.values():
        counts[v["status"]] = counts.get(v["status"], 0) + 1
    log("summary: " + ", ".join(f"{n} {s}" for s, n in sorted(counts.items())))
    return out
