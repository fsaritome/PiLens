"""Convert the Ramanujan Machine "euler2ai" π dataset to plain JSON for `pilens compare`.

Source: https://github.com/RamanujanMachine/euler2ai (Raz et al., "From Euler to AI:
Unifying Formulas for Mathematical Constants", arXiv:2502.17533). We read
``dataset/pcfs.pkl`` (canonical forms of π formulas harvested from arXiv) and
``dataset/cmf_pcfs_compact.pkl`` (representatives generated by their conservative matrix
field). The data is not redistributed here; download it yourself.

Needs pandas and sympy (not PiLens dependencies), e.g. in a separate venv:

    python -m venv rmvenv && rmvenv/Scripts/pip install pandas sympy numpy
    curl -LO https://raw.githubusercontent.com/RamanujanMachine/euler2ai/main/dataset/pcfs.pkl
    curl -LO https://raw.githubusercontent.com/RamanujanMachine/euler2ai/main/dataset/cmf_pcfs_compact.pkl
    rmvenv/Scripts/python -I scripts/import_euler2ai.py pcfs.pkl cmf_pcfs_compact.pkl data/ramanujan/euler2ai_pi.json

Pickles can run code when loaded, so this uses an unpickler that only allows pandas,
numpy and sympy classes (plus a few harmless builtins).
"""

import json
import pickle
import sys
from pathlib import Path

ALLOWED = ("pandas.", "numpy", "sympy.")
SAFE_BUILTINS = {"slice", "set", "frozenset", "complex", "list", "dict", "tuple"}


class SafeUnpickler(pickle.Unpickler):
    def find_class(self, module, name):
        if module == "builtins" and name in SAFE_BUILTINS:
            return super().find_class(module, name)
        if module.startswith(ALLOWED):
            return super().find_class(module, name)
        raise pickle.UnpicklingError(f"blocked {module}.{name}")


def main(pcfs_path, cmf_path, out_path):
    import sympy as sp

    n = sp.Symbol("n")

    def coefs(expr):
        p = sp.Poly(sp.sympify(expr), n)
        c = [int(v) for v in reversed(p.all_coeffs())]
        if any(sp.Rational(v) != v for v in p.all_coeffs()):
            raise ValueError("non-integer")
        return c

    def mobius(limit):
        num, den = sp.fraction(sp.together(sp.sympify(limit)))
        x = sp.Symbol("x")
        pn, pd = sp.Poly(num.subs(sp.pi, x), x), sp.Poly(den.subs(sp.pi, x), x)
        if pn.degree() > 1 or pd.degree() > 1:
            return None
        g = lambda P: [P.coeff_monomial(1), P.coeff_monomial(x)]
        vals = g(pn) + g(pd)
        lcm = sp.ilcm(*[sp.Rational(v).q for v in vals])
        return [int(v * lcm) for v in vals]  # (p0 + p1 π) / (q0 + q1 π)

    out = []
    for kind, path in (("literature", pcfs_path), ("cmf", cmf_path)):
        df = SafeUnpickler(open(path, "rb")).load()
        for i, row in df.iterrows():
            try:
                a, b = coefs(row["a"]), coefs(row["b"])
            except Exception as e:  # rational a/b would need inflating; report and skip
                print(f"skip {kind} {i}: {row['a']} | {row['b']} ({e})")
                continue
            src = row["sources"]
            first = ""
            if kind == "literature" and src:
                s0 = src[0]
                first = str(s0.get("formula", ""))[:200] if isinstance(s0, dict) else str(s0)[:200]
            out.append({"kind": kind, "index": int(i), "a": a, "b": b, "limit": str(row["limit"]),
                        "mobius": mobius(row["limit"]),
                        "delta": None if row["delta"] is None else float(row["delta"]),
                        "convergence_rate": None if row["convergence_rate"] is None else float(row["convergence_rate"]),
                        "n_sources": len(src) if src is not None else 0, "first_source": first})
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(json.dumps(out, indent=1), encoding="utf-8")
    print(f"wrote {len(out)} fractions to {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
